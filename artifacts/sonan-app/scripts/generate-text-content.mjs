function normalizeTranslated(value) {
  return value
    .replace(/\s+/g, ' ')
    .replace(/\s+([،.؟!?])/g, '$1')
    .trim();
}

async function translate(text, lang) {
  const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=ar&tl=${lang}&dt=t&q=${encodeURIComponent(text)}`;
  for (let attempt = 1; attempt <= 4; attempt++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`Translate failed ${res.status}`);
      const data = await res.json();
      return normalizeTranslated(data[0].map((part) => part[0]).join(''));
    } catch (error) {
      if (attempt === 4) throw error;
      await new Promise((resolve) => setTimeout(resolve, attempt * 500));
    }
  }
  return text;
}

for (const [name, collection] of Object.entries(collections)) {
  const arabic = {
    title: collection.title,
    subtitle: collection.subtitle,
    category: collection.category,
    items: collection.items.map(([title, text, source], index) => ({
      id: String(index + 1),
      title,
      text,
      source,
      category: collection.category,
    })),
  };
  await fs.writeFile(path.join(outDir, `${name}.json`), `${JSON.stringify(arabic, null, 2)}\n`, 'utf8');

  for (const lang of languages) {
    const translatedPath = path.join(outDir, `${name}.${lang}.json`);
    if (!force) {
      try {
        await fs.access(translatedPath);
        continue;
      } catch {
        // Generate only missing language files when resuming.
      }
    }

    const translated = {
      title: await translate(collection.title, lang),
      subtitle: await translate(collection.subtitle, lang),
      category: collection.category,
      items: [],
    };

    for (let index = 0; index < collection.items.length; index++) {
      const [title, text, source] = collection.items[index];
      translated.items.push({
        id: String(index + 1),
        title: await translate(title, lang),
        text: await translate(text, lang),
        source: await translate(source, lang),
        category: collection.category,
      });
      await new Promise((resolve) => setTimeout(resolve, 60));
    }

    await fs.writeFile(translatedPath, `${JSON.stringify(translated, null, 2)}\n`, 'utf8');
  }
}
